"""Generate deterministic scalar identifier tables from vendored Unicode data.

No network is used. Updating a policy requires a deliberate source/checksum edit.
Run from any directory; --check fails when the checked-in artifact is stale.
"""
import argparse
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "17.0.0/DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    "9.0.0/DerivedCoreProperties.txt": "6662c7e30b572df5d948c092692f52bcc79ab36d49a063a73d6435042db6fb3b",
    "9.0.0/UnicodeData.txt": "68dfc414d28257b9b5d6ddbb8b466c768c00ebdf6cbf7784364a9b6cad55ee8f",
}


def source(name):
    data = (ROOT / "data" / "unicode" / name).read_bytes()
    if sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError(f"Unicode source checksum mismatch: {name}")
    return data.decode("utf-8")


def derived(version):
    properties = {"ID_Start": [], "ID_Continue": []}
    for line in source(f"{version}/DerivedCoreProperties.txt").splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) < 2 or fields[1].strip() not in properties:
            continue
        ends = fields[0].strip().split("..")
        properties[fields[1].strip()].append((int(ends[0], 16), int(ends[-1], 16)))
    return properties


def categories():
    start, part = [], []
    first = None
    for line in source("9.0.0/UnicodeData.txt").splitlines():
        fields = line.split(";")
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
            continue
        low = first if name.endswith(", Last>") else cp
        first = None
        if low > 0xFFFF:
            continue
        interval = (low, min(cp, 0xFFFF))
        if category in {"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"}:
            start.append(interval)
            part.append(interval)
        elif category in {"Mn", "Mc", "Nd", "Pc"}:
            part.append(interval)
    return start, part


def boundaries(ranges, extras=()):
    ranges = sorted([*ranges, *((cp, cp) for cp in extras)])
    merged = []
    for low, high in ranges:
        if merged and low <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(high, merged[-1][1]))
        else:
            merged.append((low, high))
    return tuple(value for low, high in merged for value in (low, high + 1))


def generate():
    modern, legacy = derived("17.0.0"), derived("9.0.0")
    es5start, es5part = categories()
    tables = {
        "ID_START": boundaries(modern["ID_Start"], (0x24, 0x5F)),
        "ID_CONTINUE": boundaries(modern["ID_Continue"], (0x24, 0x5F, 0x200C, 0x200D)),
        "ES6_ID_START": boundaries(legacy["ID_Start"], (0x24, 0x5F)),
        "ES6_ID_CONTINUE": boundaries(legacy["ID_Continue"], (0x24, 0x5F, 0x200C, 0x200D)),
        "ES5_ID_START": boundaries(es5start, (0x24, 0x5F)),
        "ES5_ID_CONTINUE": boundaries(es5part, (0x24, 0x5F, 0x200C, 0x200D)),
    }
    lines = [
        '# Generated by tools/generate_unicode.py; do not edit by hand.',
        '# Unicode data copyright Unicode, Inc.; see data/unicode/LICENSE.txt.',
        '# Intervals are alternating inclusive starts / exclusive ends.',
        'UNICODE_VERSION = "17.0.0"',
        'LEGACY_UNICODE_VERSION = "9.0.0"',
        'SOURCE_SHA256 = {',
        *(f'    {name!r}: {digest!r},' for name, digest in SOURCES.items()),
        '}',
    ]
    for name, values in tables.items():
        lines.extend(["", f"{name} = ("])
        for offset in range(0, len(values), 10):
            lines.append("    " + ", ".join(f"0x{cp:X}" for cp in values[offset:offset + 10]) + ",")
        lines.append(")")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "esutils" / "_unicode_data.py"
    expected = generate()
    if args.check:
        if target.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated Unicode tables differ; run tools/generate_unicode.py")
        print("Unicode checksums and generated tables verified")
    else:
        target.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
